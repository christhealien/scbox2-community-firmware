package main

import (
	"os"
	"path/filepath"
	"testing"
)

// a router that gives out its own domain by DHCP ("office"): its names sign in like .lan ones
func TestLoginHostDHCPDomain(t *testing.T) {
	old := resolvConf
	resolvConf = filepath.Join(t.TempDir(), "resolv.conf")
	defer func() { resolvConf = old }()
	if loginHostOK("miner-1.office") {
		t.Fatal("no DHCP domain yet: refused")
	}
	os.WriteFile(resolvConf, []byte("# Generated by dhcpcd from eth0.dhcp\nsearch office\nnameserver 192.168.1.1\n"), 0o644)
	for h, want := range map[string]bool{"miner-1.office": true, "MINER-1.OFFICE.:80": true, "miner-1.office.evil.com": false, "evil.com": false, "miner.lan": true} {
		if got := loginHostOK(h); got != want {
			t.Errorf("%s: %v", h, got)
		}
	}
	os.WriteFile(resolvConf, []byte("domain com\nsearch example.org\n"), 0o644)
	if loginHostOK("evil.com") || !loginHostOK("miner.example.org") {
		t.Fatal("a bare public ending must not count; a full domain does")
	}
}
